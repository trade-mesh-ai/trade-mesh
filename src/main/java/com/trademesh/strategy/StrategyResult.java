package com.trademesh.strategy;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.LocalDateTime;

/**
 * Represents the result of strategy evaluation.
 *
 * <p>Wraps a TradeSignal with execution metadata to indicate whether the signal
 * is executable or should be skipped, along with the reason for the decision.
 *
 * <p>This is the output of the TradingStrategy.evaluate() method and serves as
 * input to the execution pipeline.
 */
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class StrategyResult {

    /**
     * The trade signal generated by the strategy.
     * May be null if the strategy decided not to generate a signal.
     */
    private TradeSignal signal;

    /**
     * Whether this signal is executable.
     * true = signal should be sent to execution pipeline.
     * false = signal should be skipped (see skipReason).
     */
    private Boolean isExecutable;

    /**
     * Reason why the signal was skipped (if isExecutable is false).
     * Examples:
     * - "VIX too high (25.5), exceeds max threshold (20.0)"
     * - "Market condition is NO_TRADE, skipping all signals"
     * - "Position already exists for this symbol"
     * - "Daily loss limit reached"
     * - "Outside trading hours"
     */
    private String skipReason;

    /**
     * Timestamp when this result was generated/evaluated.
     */
    @Builder.Default
    private LocalDateTime executedAt = LocalDateTime.now();
}
